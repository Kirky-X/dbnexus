//! db_entity 宏示例
//!
//! 演示 `#[db_entity(...)]` 统一属性宏的完整使用：
//! - 定义多个实体（User, Product, Order）使用模块隔离避免命名冲突
//! - 展示宏生成的 `table_name()` / `primary_key_column()` 辅助方法
//! - 通过 sea-orm `Relation` 枚举展示实体关系声明
//! - 在 SQLite 内存数据库中创建表并验证表名匹配
//!
//! # 运行示例
//!
//! ```bash
//! cargo run --example macros_db_entity --features "sqlite,permission,macros"
//! ```

#[path = "../common/mod.rs"]
mod common;

use dbnexus::db_entity;
use dbnexus::sea_orm::entity::prelude::*;

// ============================================
// User 实体
// ============================================

/// 用户实体模块
///
/// 使用 `#[db_entity(table_name = "users", primary_key = "id")]` 属性宏为 Model 添加：
/// - `table_name() -> &'static str`         返回表名
/// - `primary_key_column() -> &'static str` 返回主键列名
/// - 8 个 CRUD 方法（insert/find_by_id/update/delete/find_all/...）
/// - `impl ActiveModelBehavior for ActiveModel`（宏自动生成）
mod user {
    use super::*;

    /// 用户实体模型
    #[db_entity(table_name = "users", primary_key = "id")]
    #[derive(Clone, Debug, PartialEq, DeriveEntityModel)]
    #[sea_orm(table_name = "users")]
    pub struct Model {
        #[sea_orm(primary_key)]
        pub id: i64,
        pub name: String,
        pub email: String,
    }

    /// User 实体关系（本示例暂不声明关系，关注 db_entity 宏生成的元数据方法）
    #[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]
    pub enum Relation {}
}

// ============================================
// Product 实体
// ============================================

/// 产品实体模块
mod product {
    use super::*;

    /// 产品实体模型
    #[db_entity(table_name = "products", primary_key = "id")]
    #[derive(Clone, Debug, PartialEq, DeriveEntityModel)]
    #[sea_orm(table_name = "products")]
    pub struct Model {
        #[sea_orm(primary_key)]
        pub id: i64,
        pub name: String,
        pub price: f64,
        pub stock: i32,
    }

    /// Product 实体关系（本示例暂不声明关系，关注 db_entity 宏生成的元数据方法）
    #[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]
    pub enum Relation {}
}

// ============================================
// Order 实体
// ============================================

/// 订单实体模块
mod order {
    use super::*;

    /// 订单实体模型
    #[db_entity(table_name = "orders", primary_key = "id")]
    #[derive(Clone, Debug, PartialEq, DeriveEntityModel)]
    #[sea_orm(table_name = "orders")]
    pub struct Model {
        #[sea_orm(primary_key)]
        pub id: i64,
        pub user_id: i64,
        pub product_id: i64,
        pub quantity: i32,
        pub total_price: f64,
    }

    /// Order 实体关系（本示例暂不声明关系，关注 db_entity 宏生成的元数据方法）
    #[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]
    pub enum Relation {}
}

// ============================================
// 主函数
// ============================================

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    println!("========================================");
    println!("🏷️  DBNexus db_entity macro example");
    println!("========================================\n");

    // ============================================
    // 1. 展示宏生成的 table_name() 和 primary_key_column()
    // ============================================
    println!("--- 1. macro-generated metadata methods ---\n");

    println!("  [User entity]");
    println!("    table_name()         = {}", user::Model::table_name());
    println!(
        "    primary_key_column() = {}",
        user::Model::primary_key_column()
    );

    println!("\n  [Product entity]");
    println!(
        "    table_name()         = {}",
        product::Model::table_name()
    );
    println!(
        "    primary_key_column() = {}",
        product::Model::primary_key_column()
    );

    println!("\n  [Order entity]");
    println!("    table_name()         = {}", order::Model::table_name());
    println!(
        "    primary_key_column() = {}",
        order::Model::primary_key_column()
    );

    // ============================================
    // 2. 展示实体关系声明
    // ============================================
    println!("\n--- 2. entity relation declarations ---\n");

    println!(
        "  this example focuses on the metadata methods generated by the db_entity macro and declares no entity relations."
    );
    println!("  to declare relations, use the sea-orm #[sea_orm(has_many/belongs_to)] attribute.");

    // ============================================
    // 3. 创建数据库并验证表名匹配
    // ============================================
    println!("\n--- 3. create the database and verify table names ---\n");

    let (_pool, session) = common::db::setup_shared_sqlite_session().await?;
    println!("  ✓ pool and Session created (role: admin)");

    // 使用宏生成的 table_name() 动态构建 DDL
    for (table_name, ddl) in [
        (
            user::Model::table_name(),
            format!(
                "CREATE TABLE {} (id INTEGER PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL)",
                user::Model::table_name()
            ),
        ),
        (
            product::Model::table_name(),
            format!(
                "CREATE TABLE {} (id INTEGER PRIMARY KEY, name TEXT NOT NULL, price REAL NOT NULL, stock INTEGER NOT NULL)",
                product::Model::table_name()
            ),
        ),
        (
            order::Model::table_name(),
            format!(
                "CREATE TABLE {} (id INTEGER PRIMARY KEY, user_id INTEGER NOT NULL, product_id INTEGER NOT NULL, quantity INTEGER NOT NULL, total_price REAL NOT NULL)",
                order::Model::table_name()
            ),
        ),
    ] {
        session.execute_raw_ddl(&ddl).await?;
        println!("  ✓ table created: {} (DDL from table_name())", table_name);
    }

    // ============================================
    // 4. 验证 primary_key_column() 与实际列匹配
    // ============================================
    println!("\n--- 4. verify primary key column names ---\n");
    println!(
        "  User::primary_key_column()    = {} (corresponds to users.id)",
        user::Model::primary_key_column()
    );
    println!(
        "  Product::primary_key_column() = {} (corresponds to products.id)",
        product::Model::primary_key_column()
    );
    println!(
        "  Order::primary_key_column()   = {} (corresponds to orders.id)",
        order::Model::primary_key_column()
    );

    println!("\n========================================");
    println!("✨ db_entity macro example complete!");
    println!("========================================");
    println!("\n📚 Key concepts:");
    println!(
        "  - #[db_entity(table_name=\"...\", primary_key=\"...\")]  enable the unified attribute macro"
    );
    println!(
        "  - #[sea_orm(table_name = \"...\")]           specify the table name (sea-orm layer)"
    );
    println!(
        "  - #[sea_orm(primary_key)]                  mark the primary key field (sea-orm layer)"
    );
    println!(
        "  - Model::table_name() -> &'static str      the macro-generated table name accessor"
    );
    println!(
        "  - Model::primary_key_column() -> &'static str  the macro-generated primary key column accessor"
    );
    println!(
        "  - Relation enum + DeriveRelation            declare entity relations (has_many/belongs_to)"
    );
    println!(
        "\n⚠️  Note: db_entity is the unified attribute macro replacing the legacy DbEntity/db_crud/db_permission/db_cache/db_audit."
    );
    println!(
        "   the CRUD methods and ActiveModelBehavior are all generated by the macro, no manual work needed."
    );

    Ok(())
}
